def setd(key, new):
    global s
    L = s.split("\n"); hit = 0
    for i, l in enumerate(L):
        if key in l and l.startswith(' ("') and not l.startswith(' ("R"'):
            L[i] = re.sub(r', (\(.*\)|\d+|None)\),\s*$', f', {new}),', l); hit += 1
    assert hit == 1, (key, hit); s = "\n".join(L)
def after(key, items):
    global s
    L = s.split("\n")
    i = [k for k, l in enumerate(L) if key in l and l.startswith(' ("')]
    assert len(i) == 1, key
    L[i[0] + 1:i[0] + 1] = [f' ({t!r}, {d}),' for t, d in items]; s = "\n".join(L)
